"""ЛР4: преобразование числа по пяти диапазонам из задания."""


class Converter:
    @staticmethod
    def do(x: float) -> int:
        """Принять float с одним знаком после точки и вернуть int.

        Метод статический: можно вызвать Converter.do(x), не создавая объект.
        При нулевом входном значении требуется исключение ValueError.
        """
        # Большие положительные числа проверяем раньше остальных положительных.
        if x >= 100.7:
            return 1000

        if x > 0:
            return int(x)  # Отбросить дробь, а не округлить: 65.7 -> 65.

        if x == 0:
            raise ValueError("Число x не должно быть равно нулю.")

        if x >= -30.4:
            return int(x) - 5  # Например, int(-1.9) == -1, результат -6.

        # При точности один знак все оставшиеся числа не больше -30.5.
        return -2000
